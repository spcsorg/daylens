test('a line too long to decode is still read from its edges', () => {
  const c = claudeCtx()
  const p = parser(c)
  const big = claude.prompt(c, sec(0), [{ type: 'image', source: { type: 'base64', data: 'A'.repeat(3 << 20) } }, { type: 'text', text: 'what is this' }], { uuid: 'img1' })
  const recs = [...p.line(null, big.slice(0, 8192), big.slice(-8192)), ...run(p, [claude.assistant(c, sec(4), 'end_turn')])]
  assert.deepEqual(of(recs, 'user').map((u) => [u.key, u.act, u.basis, u.at]), [['img1', 'prompt', 'marked', sec(0)]])
  assert.equal(p.counts.bad, 0)
})

test('a resumed copy of a session counts each turn and act once', () => {
  const c = claudeCtx()
  const lines = [claude.prompt(c, sec(0), 'go', { uuid: 'p1' }), claude.assistant(c, sec(3), 'end_turn')]
  const a = run(parser(c), lines)
  const b = run(new ClaudeParser('other-session', null, null), lines)
  assert.deepEqual(of(a, 'turn').map((t) => t.key), of(b, 'turn').map((t) => t.key))
  assert.deepEqual(of(a, 'user').map((u) => u.key), of(b, 'user').map((u) => u.key))
})

test('state saved mid-turn resumes the same turn after a restart', () => {
  const c = claudeCtx()
  const p1 = parser(c)
  run(p1, [claude.prompt(c, sec(0), 'go', { uuid: 'p1' }), claude.assistant(c, sec(3), 'tool_use', { tools: [{ id: 't', name: 'Bash' }] })])
  const p2 = new ClaudeParser(c.session, null, p1.state())
  const recs = run(p2, [claude.toolResult(c, sec(60), 't', 'ok'), claude.assistant(c, sec(61), 'end_turn'), claude.system(c, sec(62), 'turn_duration')])
  assert.equal(of(recs, 'turn').length, 0)
  assert.deepEqual(of(recs, 'end'), [{ t: 'end', key: 'p1', state: 'completed', at: sec(62) }])
})

