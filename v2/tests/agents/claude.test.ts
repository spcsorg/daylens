import { test } from 'node:test'
import assert from 'node:assert/strict'
import { ClaudeParser } from '../../capture/agents/claude.ts'
import { claude, claudeCtx, of, run, sec } from './fixtures.ts'

const parser = (c = claudeCtx()) => new ClaudeParser(c.session, null, null)

test('a typed prompt opens a turn that ends at the turn marker, with one act at the time it was sent', () => {
  const c = claudeCtx()
  const recs = run(parser(c), [
    claude.queue(c, sec(0), 'enqueue', 'fix the build'),
    claude.queue(c, sec(0), 'dequeue'),
    claude.prompt(c, sec(0), 'fix the build', { uuid: 'p1' }),
    claude.assistant(c, sec(5), 'tool_use', { tools: [{ id: 't1', name: 'Bash' }] }),
    claude.toolResult(c, sec(30), 't1', 'ok'),
    claude.assistant(c, sec(40), 'end_turn', { text: 'done' }),
    claude.system(c, sec(41), 'turn_duration', { durationMs: 41000 }),
  ])
  const [session] = of(recs, 'session')
  assert.equal(session!.origin, 'interactive')
  assert.equal(session!.dir, c.cwd)
  assert.deepEqual(of(recs, 'turn').map((t) => [t.key, t.opener, t.start]), [['p1', 'user', sec(0)]])
  assert.deepEqual(of(recs, 'user').map((u) => [u.act, u.basis, u.at, u.turn]), [['prompt', 'marked', sec(0), 'p1']])
  assert.deepEqual(of(recs, 'end'), [{ t: 'end', key: 'p1', state: 'completed', at: sec(41) }])
  assert.equal(Math.max(...of(recs, 'activity').map((a) => a.at)), sec(40))
})

test('user-role messages a person did not type are never counted as theirs', () => {
  const c = claudeCtx()
  const recs = run(parser(c), [
    claude.prompt(c, sec(0), 'real request', { uuid: 'p1' }),
    claude.assistant(c, sec(2), 'end_turn'),
    // Injected context, skill bodies and local command output, with and without the newer origin markers.
    claude.prompt(c, sec(10), [{ type: 'text', text: 'Base directory for this skill: /x' }], { isMeta: true, origin: null }),
    claude.prompt(c, sec(11), '<local-command-caveat>Caveat: generated by local commands</local-command-caveat>', { isMeta: true, origin: null }),
    claude.prompt(c, sec(12), '<local-command-stdout>output</local-command-stdout>', { origin: null }),
    claude.prompt(c, sec(13), '<system-reminder>context</system-reminder>', { origin: null }),
    // A background task finishing, a compaction summary, another session's message, and an automatic "continue".
    claude.prompt(c, sec(20), '<task-notification>task done</task-notification>', { origin: { kind: 'task-notification' }, promptSource: 'system' }),
    claude.assistant(c, sec(22), 'end_turn'),
    claude.prompt(c, sec(30), 'This session is being continued from a previous conversation...', { compact: true, origin: null }),
    claude.prompt(c, sec(40), 'message from another session', { origin: { kind: 'peer', from: 'uds:/tmp/x' }, promptSource: 'system', isMeta: true }),
    claude.prompt(c, sec(50), 'continue', { origin: { kind: 'auto-continuation' }, promptSource: 'system', isMeta: true }),
    claude.assistant(c, sec(52), 'end_turn'),
    claude.prompt(c, sec(60), '[Cross-session idle notice] something', { isMeta: true, origin: null }),
  ])
  assert.deepEqual(of(recs, 'user').map((u) => u.at), [sec(0)])
  const openers = of(recs, 'turn').map((t) => t.opener)
  assert.deepEqual(openers, ['user', 'notification', 'continuation'])
})

